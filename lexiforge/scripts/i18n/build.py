"""Generates src/lib/i18n/en.ts and vi.ts from the part*.py sources. Run: python3 scripts/i18n/build.py"""
import glob, importlib, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import part1
for f in sorted(glob.glob(os.path.join(HERE, "part[2-9].py"))):
    importlib.import_module(os.path.basename(f)[:-3])
D = part1.D
OUT = os.path.join(HERE, "..", "..", "src", "lib", "i18n")

def emit(idx):
    lines = []
    for sec in D:
        lines.append(f"  {sec}: {{")
        for k, pair in D[sec].items():
            assert isinstance(pair, tuple) and len(pair) == 2 and pair[0] and pair[1], (sec, k)
            lines.append(f"    {k}: {json.dumps(pair[idx], ensure_ascii=False)},")
        lines.append("  },")
    return "\n".join(lines)

HDR = "// GENERATED by scripts/i18n/build.py — edit the part*.py sources, not this file.\n"
with open(os.path.join(OUT, "en.ts"), "w") as f:
    f.write(HDR + "export const en = {\n" + emit(0) + "\n} as const;\n")
with open(os.path.join(OUT, "vi.ts"), "w") as f:
    f.write(HDR + 'import type { Dict } from "./types";\n\nexport const vi: Dict = {\n' + emit(1) + "\n};\n")
print(sum(len(v) for v in D.values()), "keys in", len(D), "sections")
